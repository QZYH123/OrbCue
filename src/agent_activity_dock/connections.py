"""One-time, revocable connection of already-installed Agents.

The manager only discovers executables through PATH and writes user-level
wrapper scripts or native hook entries.  It never downloads, reinstalls, or
replaces an Agent executable.
"""
from __future__ import annotations

import json
import os
import shutil
import sys
import textwrap
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any, Optional

from .native_hooks import (
    CLAUDE_HOOK_ACTION,
    install_claude_hooks,
    uninstall_claude_hooks,
)

KNOWN_AGENTS = ("codex", "claude", "dsh")
PREFERRED_METHOD = {
    "codex": "wrapper",
    "claude": "native_hook",
    "dsh": "wrapper",
}
WRAPPER_LIMITATION = (
    "command wrapper reports start/stop/error only; it cannot detect "
    "waiting-for-input without a native Hook"
)
NATIVE_LIMITATION = (
    "native hooks report session start, permission/waiting, normal end, and "
    "failure; no transcript or terminal content is read"
)
PATH_BLOCK_START = "# >>> agent-activity-dock PATH >>>"
PATH_BLOCK_END = "# <<< agent-activity-dock PATH <<<"


@dataclass(frozen=True, slots=True)
class DiscoveredAgent:
    name: str
    path: str


@dataclass(frozen=True, slots=True)
class ConnectionRecord:
    name: str
    original: str
    method: str
    wrapper: Optional[str] = None
    hook_script: Optional[str] = None
    capabilities: tuple[str, ...] = ()
    limitation: str = ""
    installed_at: str = ""

    def to_dict(self) -> dict:
        value = asdict(self)
        value["capabilities"] = list(self.capabilities)
        return value

    @classmethod
    def from_dict(cls, value: dict) -> "ConnectionRecord":
        return cls(
            name=str(value["name"]),
            original=str(value["original"]),
            method=str(value["method"]),
            wrapper=value.get("wrapper"),
            hook_script=value.get("hook_script"),
            capabilities=tuple(value.get("capabilities", ())),
            limitation=str(value.get("limitation", "")),
            installed_at=str(value.get("installed_at", "")),
        )


@dataclass(frozen=True, slots=True)
class SetupResult:
    name: str
    status: str
    detail: str = ""


@dataclass(frozen=True, slots=True)
class SetupPlan:
    name: str
    original: str
    method: str
    status: str  # "connect" or "keep"
    detail: str = ""

    def describe(self) -> str:
        if self.status == "keep":
            return f"keep existing {self.method} connection"
        if self.method == "wrapper":
            return (
                f"create {self.bin_dir / self.name} and prepend "
                f"{self.bin_dir} to PATH in user shell rc"
            )
        if self.method == "native_hook":
            return (
                f"add revocable {self.name} hook entries to user settings.json "
                f"and create {self.hook_dir / (self.name + '-hook.py')}"
            )
        return f"connect with method {self.method}"

    @property
    def bin_dir(self) -> Path:
        return Path(
            os.environ.get("XDG_DATA_HOME", str(Path.home() / ".local" / "share"))
        ) / "agent-activity-dock" / "bin"

    @property
    def hook_dir(self) -> Path:
        return Path(
            os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config"))
        ) / "agent-activity-dock" / "hooks"


_WRAPPER_TEMPLATE = """\
#!/usr/bin/env python3
# Generated by Agent Activity Dock.  This wrapper calls the original Agent
# executable only; it sends explicit start/stop/error events and forwards
# signals.  It never reads commands, prompts, transcripts, or terminal output.
import json
import os
import signal
import subprocess
import sys
import time
import uuid

ORIGINAL = {original}
SOURCE = {source}
DOCK_CLI_CANDIDATES = {candidates_json}
FORWARDED_SIGNALS = tuple(
    getattr(signal, name) for name in ("SIGINT", "SIGTERM", "SIGHUP", "SIGQUIT")
    if hasattr(signal, name)
)


def emit(action, task_id, terminal=None):
    event_id = f"{SOURCE}-{action}-{task_id}-{uuid.uuid4().hex}"
    argv = [
        action,
        task_id,
        "--source",
        SOURCE,
        "--event-id",
        event_id,
    ]
    if terminal:
        argv.extend(["--terminal", terminal])
    for candidate in DOCK_CLI_CANDIDATES:
        try:
            proc = subprocess.run(
                candidate + ["--json", "--timeout", "0.25"] + argv,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                timeout=1.0,
            )
        except (OSError, subprocess.SubprocessError):
            continue
        if proc.returncode in (0, 1):
            return True
    return False


def main():
    task_id = (
        os.environ.get("AGENT_ACTIVITY_DOCK_TASK_ID")
        or os.environ.get("AADOCK_TASK_ID")
        or f"{SOURCE}-{os.getpid()}-{uuid.uuid4().hex[:10]}"
    )
    terminal = os.environ.get("AGENT_ACTIVITY_DOCK_TERMINAL") or os.environ.get(
        "AADOCK_TERMINAL"
    )
    emit("start", task_id, terminal)

    child = subprocess.Popen([ORIGINAL] + sys.argv[1:])
    old_handlers = {}
    for signum in FORWARDED_SIGNALS:
        old_handlers[signum] = signal.getsignal(signum)

    def forward(signum, frame):  # noqa: ARG001
        if child.poll() is None:
            child.send_signal(signum)

    for signum in FORWARDED_SIGNALS:
        signal.signal(signum, forward)

    returncode = child.wait()
    for signum, handler in old_handlers.items():
        signal.signal(signum, handler)

    emit("error" if returncode != 0 else "stop", task_id, terminal)

    if returncode < 0:
        signum = -returncode
        signal.signal(signum, signal.SIG_DFL)
        os.kill(os.getpid(), signum)
        time.sleep(0.2)
        os._exit(128 + signum)
    if returncode >= 128 and (returncode - 128) in FORWARDED_SIGNALS:
        signum = returncode - 128
        signal.signal(signum, signal.SIG_DFL)
        os.kill(os.getpid(), signum)
        time.sleep(0.2)
        os._exit(returncode)
    raise SystemExit(returncode if 0 <= returncode <= 255 else 1)


if __name__ == "__main__":
    main()
"""

